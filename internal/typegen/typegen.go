// Package typegen generates TypeScript declarations from Go structs (TG-01 …
// TG-05).
//
// It reads Go source with go/ast rather than compiling and reflecting, because
// the source carries the `json` and `validate` tags that the generated types must
// respect, and because it has to work on a project that does not build yet.
//
// Scope is deliberately a subset. The mapping covered today:
//
//	string, []byte              -> string
//	int, uint, float, complex   -> number
//	bool                        -> boolean
//	time.Time                   -> string   (ISO 8601 over JSON)
//	[]T                         -> T[]
//	map[string]T                -> Record<string, T>
//	*T                          -> T | null
//	any, interface{}            -> unknown
//	named struct                -> its interface
//	embedded vuepher.Model      -> id, created_at, updated_at
//
// Anything outside that set becomes `unknown` with a comment naming the Go type,
// which keeps the output valid rather than silently wrong (R3).
package typegen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/vuepher/vuepher/support"
)

// Options configure a generation run.
type Options struct {
	// Sources are directories, relative to Root, to read Go files from.
	Sources []string

	// Out is the output directory, relative to Root.
	Out string

	// Root is the project root. Defaults to the current directory.
	Root string

	// Check leaves the filesystem untouched and reports whether the generated
	// output is already up to date, for TG-08's CI mode.
	Check bool

	// Header is prepended to each generated file.
	Header string
}

// Result reports what a run produced.
type Result struct {
	// Files are the paths written, relative to Root.
	Files []string

	// Types are the Go type names converted, for the CLI summary.
	Types []string

	// Pages maps a Vue component name to the props type that backs it (TG-05).
	Pages map[string]string

	// Warnings are the constructs that fell back to `unknown`, so the errors are
	// discoverable rather than hidden in the output.
	Warnings []string

	// Stale is set in Check mode when the output differs from what is on disk.
	Stale []string
}

const defaultHeader = `// Code generated by vuepher types:generate. DO NOT EDIT.
//
// These declarations are derived from Go structs: the json tag becomes the
// property name, the Go type becomes the TypeScript type. Re-run
// ` + "`vuepher types:generate`" + ` after changing a struct.
`

// Generate reads the sources and writes declarations.
func Generate(options Options) (*Result, error) {
	opts := options
	if opts.Root == "" {
		wd, err := os.Getwd()
		if err != nil {
			return nil, err
		}
		opts.Root = wd
	}
	if opts.Out == "" {
		opts.Out = filepath.Join("resources", "js", "types", "generated")
	}
	if opts.Header == "" {
		opts.Header = defaultHeader
	}
	if len(opts.Sources) == 0 {
		opts.Sources = []string{
			filepath.Join("app", "models"),
			filepath.Join("app", "requests"),
			filepath.Join("app", "controllers"),
		}
	}

	run := &run{
		opts:      opts,
		result:    &Result{Pages: map[string]string{}},
		fset:      token.NewFileSet(),
		generated: generatedTypes{},
	}

	packages, err := run.collect()
	if err != nil {
		return run.result, err
	}

	if err := run.render(packages); err != nil {
		return run.result, err
	}
	return run.result, nil
}

// run carries the state of one generation pass.
type run struct {
	opts   Options
	result *Result
	fset   *token.FileSet

	// generated is every type name this run emits, by package name. It is filled
	// in while parsing and consumed when structs are converted, which is why
	// conversion is a second pass: a props struct may be declared before the
	// model it refers to is read.
	generated generatedTypes

	// pending holds struct declarations waiting for the second pass.
	pending []pendingStruct
}

// pendingStruct is a struct declaration recorded during parsing.
type pendingStruct struct {
	pkg   *pkg
	name  string
	node  *ast.StructType
	named map[string]ast.Expr
}

// pkg is one directory's worth of declarations.
type pkg struct {
	name    string
	dir     string
	structs []*structInfo
	enums   []*enumInfo

	// types are the named type declarations in the directory, across every file,
	// so a field can reference a type declared in a sibling file.
	types map[string]ast.Expr
}

type structInfo struct {
	name   string
	fields []fieldInfo
	doc    string
}

type fieldInfo struct {
	name     string
	jsonName string
	tsType   string
	optional bool
	doc      string
}

type enumInfo struct {
	name    string
	values  []string
	numeric bool
}

// collect walks the sources and gathers declarations.
func (r *run) collect() ([]*pkg, error) {
	byDir := map[string]*pkg{}
	var order []string

	for _, source := range r.opts.Sources {
		dir := source
		if !filepath.IsAbs(dir) {
			dir = filepath.Join(r.opts.Root, source)
		}
		info, err := os.Stat(dir)
		if err != nil || !info.IsDir() {
			// A project without app/requests yet is normal, not an error.
			continue
		}

		entries, err := os.ReadDir(dir)
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") ||
				strings.HasSuffix(entry.Name(), "_test.go") {
				continue
			}
			path := filepath.Join(dir, entry.Name())
			if err := r.parseFile(path, byDir, &order); err != nil {
				return nil, err
			}
		}
	}

	// Second pass: convert the recorded structs now that every generated type
	// name is known, so a reference to a type in another package resolves to the
	// interface this run emits instead of falling back to `unknown`.
	for _, item := range r.pending {
		item.pkg.structs = append(item.pkg.structs, r.buildStruct(item.name, item.node, item.named))
		r.result.Types = append(r.result.Types, item.name)
	}

	packages := make([]*pkg, 0, len(order))
	for _, dir := range order {
		p := byDir[dir]
		if len(p.structs) == 0 && len(p.enums) == 0 {
			continue
		}
		sort.Slice(p.structs, func(i, j int) bool { return p.structs[i].name < p.structs[j].name })
		packages = append(packages, p)
	}
	return packages, nil
}

// parseFile extracts declarations from one file and records the
// component-to-props-type map from view calls (TG-05).
func (r *run) parseFile(path string, byDir map[string]*pkg, order *[]string) error {
	file, err := parser.ParseFile(r.fset, path, nil, parser.ParseComments)
	if err != nil {
		// A file that does not parse is reported with its path; the rest of the
		// run continues so one broken file does not blank the output.
		r.result.Warnings = append(r.result.Warnings, fmt.Sprintf("%s could not be parsed: %v", support.RelativeTo(r.opts.Root, path), err))
		return nil
	}

	dir := filepath.Dir(path)
	p, ok := byDir[dir]
	if !ok {
		p = &pkg{name: file.Name.Name, dir: dir, types: map[string]ast.Expr{}}
		byDir[dir] = p
		*order = append(*order, dir)
	}

	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			switch d.Tok {
			case token.TYPE:
				for _, spec := range d.Specs {
					typeSpec, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					// Named type declarations, so a field referring to another named
					// type is emitted as a reference rather than as its underlying
					// type. The map lives on the package, so a reference to a type in a
					// sibling file resolves too.
					p.types[typeSpec.Name.Name] = typeSpec.Type
					r.recordGenerated(p.name, typeSpec.Name.Name)

					structType, isStruct := typeSpec.Type.(*ast.StructType)
					if !isStruct {
						continue
					}
					r.pending = append(r.pending, pendingStruct{
						pkg:   p,
						name:  typeSpec.Name.Name,
						node:  structType,
						named: p.types,
					})
				}
			case token.CONST:
				if enum := r.buildEnum(d); enum != nil {
					p.enums = append(p.enums, enum)
					r.recordGenerated(p.name, enum.name)
				}
			}
		case *ast.FuncDecl:
			r.recordViewCalls(d)
		}
	}
	return nil
}

// recordGenerated notes that a package produces a type name, so a field that
// refers to it can be emitted as a reference.
func (r *run) recordGenerated(pkg, name string) {
	if r.generated == nil {
		r.generated = generatedTypes{}
	}
	if r.generated[pkg] == nil {
		r.generated[pkg] = map[string]bool{}
	}
	r.generated[pkg][name] = true
}

// buildStruct converts a struct declaration.
func (r *run) buildStruct(name string, node *ast.StructType, named map[string]ast.Expr) *structInfo {
	info := &structInfo{name: name}

	for _, field := range node.Fields.List {
		if len(field.Names) == 0 {
			// An embedded field. The framework's base model is expanded because
			// every model has those columns and the frontend needs them typed.
			if expanded, ok := embeddedModelFields(field.Type); ok {
				info.fields = append(info.fields, expanded...)
				continue
			}
			continue
		}
		for _, ident := range field.Names {
			if !ident.IsExported() {
				continue
			}
			jsonName, options := parseJSONTag(field.Tag)
			if jsonName == "-" {
				continue
			}
			if jsonName == "" {
				jsonName = jsonTagName(ident.Name)
			}

			converted, warning := ConvertExpr(field.Type, named, r.generated)
			if warning != "" {
				r.result.Warnings = append(r.result.Warnings,
					fmt.Sprintf("%s.%s: %s", name, ident.Name, warning))
			}

			optional := options["omitempty"] != "" ||
				strings.HasPrefix(converted, "undefined")
			if _, isPointer := field.Type.(*ast.StarExpr); isPointer {
				// A pointer is nullable rather than optional: the key is always
				// present in the JSON, its value may be null.
				converted = strings.TrimPrefix(converted, "undefined | ")
			}

			info.fields = append(info.fields, fieldInfo{
				name:     ident.Name,
				jsonName: jsonName,
				tsType:   converted,
				optional: optional,
				doc:      docText(field.Doc, field.Comment),
			})
		}
	}
	return info
}

// buildEnum turns a typed const block into a TypeScript union (TG-04).
func (r *run) buildEnum(decl *ast.GenDecl) *enumInfo {
	for _, spec := range decl.Specs {
		valueSpec, ok := spec.(*ast.ValueSpec)
		if !ok || valueSpec.Type == nil {
			continue
		}
		ident, ok := valueSpec.Type.(*ast.Ident)
		if !ok {
			continue
		}
		enum := &enumInfo{name: ident.Name}
		for _, value := range valueSpec.Values {
			literal, ok := value.(*ast.BasicLit)
			if !ok {
				continue
			}
			if literal.Kind == token.STRING {
				text, err := strconv.Unquote(literal.Value)
				if err != nil {
					continue
				}
				enum.values = append(enum.values, strconv.Quote(text))
				continue
			}
			enum.values = append(enum.values, literal.Value)
			enum.numeric = true
		}
		if len(enum.values) > 0 {
			return enum
		}
	}
	return nil
}

// recordViewCalls finds vuepher.View[Props](ctx, "Component", ...) and
// ctx.View("Component", ...) calls and records which props type backs which
// component (TG-05).
func (r *run) recordViewCalls(fn *ast.FuncDecl) {
	if fn.Body == nil {
		return
	}
	ast.Inspect(fn.Body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}

		// vuepher.View[PostsIndexProps](ctx, "Posts/Index", props)
		if indexExpr, ok := call.Fun.(*ast.IndexExpr); ok {
			if !isViewSelector(indexExpr.X) {
				return true
			}
			component := stringLiteralArg(call, 1)
			if component == "" {
				return true
			}
			if ident, ok := indexExpr.Index.(*ast.Ident); ok {
				r.result.Pages[component] = ident.Name
			}
			return true
		}

		// ctx.View("Posts/Index", props): the props type is not named, so the
		// component is recorded with an untyped page.
		if selector, ok := call.Fun.(*ast.SelectorExpr); ok && selector.Sel.Name == "View" {
			component := stringLiteralArg(call, 0)
			if component != "" {
				if _, exists := r.result.Pages[component]; !exists {
					r.result.Pages[component] = ""
				}
			}
		}
		return true
	})
}

// isViewSelector reports whether an expression is the vuepher.View identifier.
func isViewSelector(node ast.Expr) bool {
	selector, ok := node.(*ast.SelectorExpr)
	if !ok || selector.Sel.Name != "View" {
		return false
	}
	ident, ok := selector.X.(*ast.Ident)
	return ok && ident.Name == "vuepher"
}

// stringLiteralArg returns the string literal at an argument position.
func stringLiteralArg(call *ast.CallExpr, index int) string {
	if index >= len(call.Args) {
		return ""
	}
	literal, ok := call.Args[index].(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return ""
	}
	text, err := strconv.Unquote(literal.Value)
	if err != nil {
		return ""
	}
	return text
}

// render writes the declaration files.
func (r *run) render(packages []*pkg) error {
	contents := map[string]string{}

	for _, p := range packages {
		var buf bytes.Buffer
		buf.WriteString(r.opts.Header)
		buf.WriteString("\n")

		for _, enum := range p.enums {
			fmt.Fprintf(&buf, "export type %s = %s\n\n", enum.name, strings.Join(enum.values, " | "))
		}
		for _, structure := range p.structs {
			writeStruct(&buf, structure)
		}
		contents[filepath.Join(r.opts.Out, p.name+".d.ts")] = buf.String()
	}

	// Pages map component names to their props types, which is what gives a Vue
	// component typed props without hand-writing an interface.
	if len(r.result.Pages) > 0 {
		var buf bytes.Buffer
		buf.WriteString(r.opts.Header)
		buf.WriteString("\n/**\n * Maps each Vue component to the props type its controller sends.\n *\n * Usage in a page component:\n *\n *   import type { PageProps } from '@/types/generated/pages'\n *   defineProps<PageProps['Posts/Index']>()\n */\nexport interface PageProps {\n")
		components := make([]string, 0, len(r.result.Pages))
		for component := range r.result.Pages {
			components = append(components, component)
		}
		sort.Strings(components)
		for _, component := range components {
			propsType := r.result.Pages[component]
			if propsType == "" {
				// A ctx.View call with an anonymous props map: the shape is not
				// knowable statically, so it is typed loosely rather than
				// guessed.
				fmt.Fprintf(&buf, "  %q: Record<string, unknown>\n", component)
				continue
			}
			fmt.Fprintf(&buf, "  %q: %s\n", component, propsType)
		}
		buf.WriteString("}\n")
		contents[filepath.Join(r.opts.Out, "pages.d.ts")] = buf.String()
	}

	// A barrel file so consumers can import everything from one path.
	var barrel bytes.Buffer
	barrel.WriteString(r.opts.Header)
	barrel.WriteString("\n")
	names := make([]string, 0, len(packages))
	for _, p := range packages {
		names = append(names, p.name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&barrel, "export * from './%s'\n", name)
	}
	if len(r.result.Pages) > 0 {
		barrel.WriteString("export * from './pages'\n")
	}
	contents[filepath.Join(r.opts.Out, "index.d.ts")] = barrel.String()

	// Write, or compare in check mode.
	paths := make([]string, 0, len(contents))
	for path := range contents {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	for _, path := range paths {
		relative := support.RelativeTo(r.opts.Root, path)
		if r.opts.Check {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, []byte(contents[path])) {
				r.result.Stale = append(r.result.Stale, relative)
			}
			continue
		}
		if err := support.WriteFile(path, []byte(contents[path]), true); err != nil {
			return err
		}
		r.result.Files = append(r.result.Files, relative)
	}
	return nil
}

// writeStruct renders one interface.
func writeStruct(buf *bytes.Buffer, structure *structInfo) {
	if structure.doc != "" {
		fmt.Fprintf(buf, "/** %s */\n", structure.doc)
	}
	fmt.Fprintf(buf, "export interface %s {\n", structure.name)
	for _, field := range structure.fields {
		if field.doc != "" {
			fmt.Fprintf(buf, "  /** %s */\n", field.doc)
		}
		optional := ""
		if field.optional {
			optional = "?"
		}
		fmt.Fprintf(buf, "  %s%s: %s\n", field.jsonName, optional, field.tsType)
	}
	buf.WriteString("}\n\n")
}

// embeddedModelFields expands the framework base model (DB-02) into the columns
// every model carries, so the frontend does not have to know about it.
func embeddedModelFields(expr ast.Expr) ([]fieldInfo, bool) {
	name := qualifiedName(expr)
	switch name {
	case "vuepher.Model", "orm.Model":
		return []fieldInfo{
			{jsonName: "id", tsType: "number"},
			{jsonName: "created_at", tsType: "string"},
			{jsonName: "updated_at", tsType: "string"},
		}, true
	default:
		return nil, false
	}
}

// qualifiedName renders an expression as a dotted name, or "".
func qualifiedName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		prefix := qualifiedName(e.X)
		if prefix == "" {
			return e.Sel.Name
		}
		return prefix + "." + e.Sel.Name
	case *ast.StarExpr:
		return qualifiedName(e.X)
	default:
		return ""
	}
}

// parseJSONTag reads the json tag, returning the name and its options.
func parseJSONTag(tag *ast.BasicLit) (string, map[string]string) {
	options := map[string]string{}
	if tag == nil {
		return "", options
	}
	value, err := strconv.Unquote(tag.Value)
	if err != nil {
		return "", options
	}
	const key = "json:"
	index := strings.Index(value, key)
	if index < 0 {
		return "", options
	}
	raw := value[index+len(key):]
	raw = strings.TrimPrefix(raw, `"`)
	// The tag value ends at the next unescaped quote.
	if end := strings.Index(raw, `"`); end >= 0 {
		raw = raw[:end]
	}
	parts := strings.Split(raw, ",")
	name := parts[0]
	for _, option := range parts[1:] {
		options[option] = option
	}
	return name, options
}

// jsonTagName converts a Go field name to the snake_case key encoding/json would
// produce with no tag, so the generated property still matches the JSON.
func jsonTagName(field string) string {
	return support.Snake(field)
}

// docText flattens a doc comment to a single line.
func docText(doc *ast.CommentGroup, trailing *ast.CommentGroup) string {
	group := doc
	if group == nil {
		group = trailing
	}
	if group == nil {
		return ""
	}
	text := strings.ReplaceAll(group.Text(), "\n", " ")
	return strings.TrimSpace(strings.Join(strings.Fields(text), " "))
}
